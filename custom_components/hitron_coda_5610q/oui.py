def lookup_oui(mac: str) -> str | None:
    """Return the manufacturer name for a MAC address, or None if unknown."""
    if not mac:
        return None
    # Normalize to upper-case with colons, then take the first 3 octets.
    normalized = mac.upper().replace("-", ":").replace(" ", "")
    if len(normalized) == 12:
        normalized = ":".join(normalized[i:i + 2] for i in range(0, 12, 2))
    oui = normalized[:8]
    return _OUI_TABLE.get(oui)
